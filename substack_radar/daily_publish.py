# 發文時間實驗（2026-10-17 信哥拍板）：後台數據看起來 10–19 點比早上好，但那跟時期混在一起，
# 不能當結論。兩組的寫稿完全相同（04:00 寫一次），只差寄出時間：ISO 單數週早上 07:30、
# 雙數週傍晚 17:00。各只有一個時段、沒有補發。實驗外一律早上。
SEND_EXPERIMENT = (date(2026, 10, 19), date(2026, 11, 15))


def send_arm(day: date) -> str:
    start, end = SEND_EXPERIMENT
    if start <= day <= end and day.isocalendar()[1] % 2 == 0:
        return "evening"
    return "morning"


def slot_now(now: datetime | None = None) -> str:
    return "evening" if (now or datetime.now()).hour >= 16 else "morning"


def link_series_part1(api, cand, url: str, ledger: dict) -> bool:
    """週末系列：下篇發出後，在昨天的上篇文末補一行「下篇已出」連結（只更新網頁，不寄信）。"""
    if (cand.meta.get("source") or {}).get("series_part") != 2:
        return False
    prev = ledger.get((date.today() - timedelta(days=1)).isoformat()) or {}
    if not prev.get("draft_id") or prev.get("series_next_url"):
        return False
    d = api.get_draft(int(prev["draft_id"]))
    body = json.loads(d["draft_body"]) if isinstance(d["draft_body"], str) else d["draft_body"]
    content = body.get("content") or []
    # 插在文末「本文取材」那條分隔線之前；找不到就放最後
    at = next((i for i, n in enumerate(content) if n.get("type") == "horizontal_rule"
               and i + 1 < len(content) and "本文取材" in _node_text(content[i + 1])), len(content))
    link = {"type": "paragraph", "content": [
        {"type": "text", "text": "👉 週末拆解下篇已出：", "marks": [{"type": "strong"}]},
        {"type": "text", "text": cand.headline, "marks": [{"type": "link", "attrs": {"href": url}}]},
    ]}
    body["content"] = content[:at] + [link] + content[at:]
    api.put_draft(int(prev["draft_id"]), draft_body=json.dumps(body))
    api.publish_draft(int(prev["draft_id"]), send=False, share_automatically=False)
    prev["series_next_url"] = url
    _save_ledger(ledger)
    print(f"[DailyPublish] 🔗 已在上篇文末補上下篇連結")
    return True


def run(day: date, *, dry_run: bool = False) -> int:
    from dotenv import load_dotenv

    load_dotenv(REPO / ".env", override=True)
    ledger = _load_ledger()
    key = day.isoformat()
    if (ledger.get(key) or {}).get("post_url"):
        print(f"[DailyPublish] 今天已經發過：{ledger[key]['post_url']}")
        return 0

    from substack import Api

    api = Api(cookies_string=os.environ["SUBSTACK_COOKIES_STRING"],
              publication_url=os.environ["SUBSTACK_PUBLICATION_URL"])

    if (ledger.get(key) or {}).get("publish_attempted_at") and not dry_run:
        url = _readback_url(api, ledger[key]["draft_id"])
        if url:
            ledger[key].update(post_url=url)
            _save_ledger(ledger)
            print(f"[DailyPublish] 之前的發布其實成功了：{url}")
        else:
            print("[DailyPublish] 🛑 之前嘗試過發布但查不到結果，為避免重寄信，今天不再發。")
            notify("每日發文需要你看一下", "早上的發布結果不明，請到 Substack 確認")
        return 0

    arm, slot = send_arm(day), slot_now()
    if not dry_run and arm != slot:
        print(f"[DailyPublish] 今天是發文時間實驗的「{arm}」組，這個時段（{slot}）不發")
        return 0

    plan = plan_for(day)
    deadline = time.monotonic() + (0 if dry_run else WAIT_FOR_PRODUCTION_S)
    chosen_plan = None
    while True:
        # 當天首選專欄還在寫（06:00／06:30 的排程沒跑完）就先等，不要急著發備胎。
        first_day, first_col = plan[0]
        pool = [c for c in candidates(first_day, first_col, ledger) if still_on_substack(api, c)]
        if pool:
            chosen_plan = (first_day, first_col, pool)
            break
        if not production_running() or time.monotonic() >= deadline:
            break
        print("[DailyPublish] 今天的稿子還在寫，等一分鐘再看")
        time.sleep(60)

    if not chosen_plan:
        for plan_day, column in plan[1:]:
            pool = [c for c in candidates(plan_day, column, ledger) if still_on_substack(api, c)]
            if pool:
                chosen_plan = (plan_day, column, pool)
                break
    if not chosen_plan:
        print("[DailyPublish] 🛑 今天沒有可以發的稿子")
        if not dry_run:
            notify("今天沒有自動發文", "排程沒有產出可發的稿子，請看一下草稿匣")
            try:
                from src.notify import notify_substack_failure
                notify_substack_failure(
                    mode="daily_publish",
                    error_msg=f"{day.isoformat()} 沒有通過審稿的稿子，今天不自動發文（不硬發），請到 Substack 草稿匣確認",
                    extra_context={"今天的專欄": plan_for(day)[0][1], "草稿匣": "沒過的稿子還在草稿匣，看過覺得可以就手動發布"},
                )
            except Exception:
                pass
        return 0

    _, column, pool = chosen_plan
    cand, reason = pick(pool)
    print(f"[DailyPublish] 選中：{cand.meta.get('title')}（{reason}；候選 {len(pool)} 篇）")
    if dry_run:
        print("[DailyPublish] （試跑，不發）")
        return 0

    url = publish(api, cand, ledger, key, reason)
    if not url:
        print("[DailyPublish] ⚠️ 已送出發布，但還查不到公開網址")
        notify("每日發文需要你看一下", f"「{cand.headline}」已送出，但還查不到公開網址")
        return 1
    print(f"[DailyPublish] ✅ 已發布並寄信：{url}")
    try:
        link_series_part1(api, cand, url, ledger)
    except Exception as exc:
        print(f"[DailyPublish] ⚠️ 回補上篇連結失敗（不影響今天的發文）：{exc}")
    update_fb_link(cand, url)
    notify("今天的文章發出去了", cand.headline)
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="每天早上自動發布一篇 Substack")
    ap.add_argument("--dry-run", action="store_true", help="只挑稿，不發")
    ap.add_argument("--date", help="指定日期 YYYY-MM-DD（預設今天）")
    args = ap.parse_args(argv)
    day = date.fromisoformat(args.date) if args.date else date.today()
    return run(day, dry_run=args.dry_run)


if __name__ == "__main__":
    sys.exit(main())

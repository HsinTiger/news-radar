"""每天早上 07:30 自動發布一篇（2026-10-15 信哥拍板）。

規則
----
- 週一～週五發「吹牛免稅」（Podcast 精選），週六、日發「賺錢有道」（公司分析）。
- 稿子來自當天早上 06:00／06:30 的排程（scripts/substack_editorial_worker.sh）。
  當天沒有符合的稿子時：週末改發當天的 Podcast；平日改發前一天沒發出去的 Podcast；
  都沒有就這天不發，並通知。主編精選（手動投稿）永遠只留草稿，不會被自動發。
- 同一欄有好幾篇時，請一個模型以「對商業有興趣的上班族」為讀者挑最值得發的一篇；
  模型不可用就挑稽核警告最少、最新的那篇。
- 發布前把內文最上面的「🧠 產文路線：…模型…稽核…」引言框拿掉，讀者看到的只有
  人寫的痕跡；其他沒發的草稿照舊保留。發布同時寄信給訂閱者。
- 你把某篇草稿刪掉（Substack 上找不到）＝否決，系統會改挑別篇。

安全
----
- 一天只發一篇：紀錄在 data/substack_drafts/.daily_published.json。
- 發布前先寫「已嘗試」：之後任何一次重跑都只回頭查有沒有發成，絕不重寄信。
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import time
from dataclasses import dataclass, field
from datetime import date, datetime, timedelta
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

DRAFTS_DIR = REPO / "data" / "substack_drafts"
LEDGER_PATH = DRAFTS_DIR / ".daily_published.json"
LOCAL_LOCK = REPO / ".runtime-state-local.lock.d"
EDITORIAL_WANT = REPO / ".runtime-state-editorial-want"
PUB_HOME = "https://hsin73.substack.com"

PODCAST, COMPANY = "吹牛免稅", "賺錢有道"
AI_COLUMN = "智取未來"          # 週二、四（2026-10-18）
WAIT_FOR_PRODUCTION_S = int(os.getenv("DAILY_PUBLISH_WAIT_S", str(45 * 60)))
FACT_FAIL_MARK = "[品質迴圈未通過]"
AI_TRACE_MARKERS = ("產文路線", "Generated by", "🧠")


# ---------------------------------------------------------------------------
# 今天發哪一欄
# ---------------------------------------------------------------------------

def plan_for(day: date) -> list[tuple[date, str]]:
    """依序嘗試的（日期, 專欄）。第一個有稿子的就發。"""
    if day.weekday() >= 5:                       # 週六、日：財報日
        return [(day, COMPANY), (day, PODCAST)]
    if day.weekday() in (1, 3):                  # 週二、四：AI 專欄，寫不出合格的才發 podcast
        return [(day, AI_COLUMN), (day, PODCAST), (day - timedelta(days=1), PODCAST)]
    return [(day, PODCAST), (day - timedelta(days=1), PODCAST)]


# ---------------------------------------------------------------------------
# 候選
# ---------------------------------------------------------------------------

@dataclass
class Candidate:
    folder: Path
    meta: dict
    column: str
    headline: str
    draft_id: str
    created_at: str
    warnings: list = field(default_factory=list)

    @property
    def rel(self) -> str:
        return str(self.folder.relative_to(DRAFTS_DIR))


def _load_ledger() -> dict:
    try:
        return json.loads(LEDGER_PATH.read_text(encoding="utf-8"))
    except Exception:
        return {}


def _save_ledger(ledger: dict) -> None:
    LEDGER_PATH.parent.mkdir(parents=True, exist_ok=True)
    tmp = LEDGER_PATH.with_suffix(".tmp")
    tmp.write_text(json.dumps(ledger, ensure_ascii=False, indent=2), encoding="utf-8")
    tmp.replace(LEDGER_PATH)


def candidates(day: date, column: str, ledger: dict) -> list[Candidate]:
    from substack_radar.fb_follow import split_column

    published = {v.get("folder") for v in ledger.values() if v.get("post_url")}
    found = []
    for meta_path in sorted((DRAFTS_DIR / day.isoformat()).glob("*/metadata.json")):
        try:
            meta = json.loads(meta_path.read_text(encoding="utf-8"))
        except Exception:
            continue
        col, headline = split_column(meta.get("title", ""))
        draft_id = str(meta.get("substack_draft_id") or "")
        warnings = [str(w) for w in meta.get("audit_warnings") or []]
        cand = Candidate(meta_path.parent, meta, col, headline, draft_id,
                         meta.get("created_at", ""), warnings)
        if col != column or not draft_id or cand.rel in published:
            continue
        if any(w.startswith(FACT_FAIL_MARK) for w in warnings):
            print(f"[DailyPublish] ⏭️ {cand.rel}：事實稽核沒過，不發")
            continue
        found.append(cand)
    return found


def still_on_substack(api, cand: Candidate) -> bool:
    """草稿還在、而且還沒發過。被刪掉（404）＝主編否決。"""
    try:
        draft = api.get_draft(int(cand.draft_id))
    except Exception as exc:
        if "404" in str(exc):
            print(f"[DailyPublish] ⏭️ {cand.rel}：Substack 上已刪除，視為否決")
            return False
        raise
    return not draft.get("is_published")


# ---------------------------------------------------------------------------
# 挑一篇
# ---------------------------------------------------------------------------

def _excerpt(cand: Candidate) -> str:
    try:
        text = (cand.folder / "Article_Substack.md").read_text(encoding="utf-8")
    except Exception:
        return ""
    body = [ln for ln in text.splitlines() if ln.strip() and not ln.startswith(("#", ">", "*"))]
    return " ".join(body)[:600]


def pick(cands: list[Candidate]) -> tuple[Candidate, str]:
    if len(cands) == 1:
        return cands[0], "只有一篇"
    try:
        import asyncio

        from pydantic import BaseModel, Field

        from src.llm_brain import call_for_json

        class Choice(BaseModel):
            choice: int = Field(..., description="選中的編號（從 1 開始）")
            reason: str = Field(..., description="一句話理由")

        listing = "\n\n".join(
            f"【{i}】{c.headline}\n副標：{c.meta.get('subtitle', '')}\n開頭：{_excerpt(c)}"
            for i, c in enumerate(cands, 1)
        )
        result = asyncio.run(call_for_json(
            system="你是一份商業電子報的總編輯。",
            prompt=(
                "今天早上 7:30 要從下面幾篇草稿挑一篇正式發出去並寄給訂閱者。\n"
                "讀者是對商業有興趣的上班族：他們通勤時打開信，想要「讀完有收穫、能拿去用、"
                "標題讓人想點開」的內容。挑對他們最有價值的那一篇。\n\n" + listing
            ),
            response_model=Choice,
            timeout_s=300,
            backends=("antigravity_cli", "gemini"),
        ))
        if result.data and 1 <= result.data.choice <= len(cands):
            return cands[result.data.choice - 1], f"總編輯模型：{result.data.reason}"
    except Exception as exc:
        print(f"[DailyPublish] ⚠️ 挑稿模型不可用，改用規則：{str(exc)[:120]}")
    newest_first = sorted(cands, key=lambda c: c.created_at, reverse=True)
    best = min(newest_first, key=lambda c: len(c.warnings))   # 警告最少；同分取最新
    return best, "規則：稽核警告最少"


# ---------------------------------------------------------------------------
# 拿掉 AI 痕跡
# ---------------------------------------------------------------------------

def _node_text(node: dict) -> str:
    if "content" in node:
        return "".join(_node_text(child) for child in node["content"])
    return node.get("text", "")


def strip_ai_traces(body: dict) -> tuple[dict, int]:
    """拿掉內文最上層含「產文路線」之類的段落（目前就是開頭那個 🧠 引言框）。"""
    content = body.get("content") or []
    kept = [n for n in content if not any(m in _node_text(n) for m in AI_TRACE_MARKERS)]
    return {**body, "content": kept}, len(content) - len(kept)


def _has_ai_trace(body: dict) -> bool:
    return any(any(m in _node_text(n) for m in AI_TRACE_MARKERS) for n in body.get("content") or [])


# ---------------------------------------------------------------------------
# 發布
# ---------------------------------------------------------------------------

def _readback_url(api, draft_id: str) -> str | None:
    posts = api.get_published_posts(offset=0, limit=25, order_by="post_date", order_direction="desc")
    items = posts.get("posts", posts) if isinstance(posts, dict) else posts
    for post in items or []:
        if str(post.get("id")) == str(draft_id):
            return post.get("canonical_url") or f"{PUB_HOME}/p/{post.get('slug')}"
    return None


def publish(api, cand: Candidate, ledger: dict, key: str, reason: str) -> str | None:
    entry = ledger.get(key) or {}
    if entry.get("publish_attempted_at"):
        # 上一次可能已經發出去（或寄出信）只是沒收到回應：只查，不重寄。
        print("[DailyPublish] 之前已嘗試發布，只回頭確認，不重寄")
        return _readback_url(api, entry["draft_id"])

    draft = api.get_draft(int(cand.draft_id))
    body = json.loads(draft["draft_body"])
    clean, removed = strip_ai_traces(body)
    if removed:
        api.put_draft(int(cand.draft_id), draft_body=json.dumps(clean, ensure_ascii=False))
        check = json.loads(api.get_draft(int(cand.draft_id))["draft_body"])
        if _has_ai_trace(check):
            raise RuntimeError("AI 痕跡沒有從 Substack 草稿拿乾淨，停止發布")
        print(f"[DailyPublish] 已拿掉 {removed} 段 AI 痕跡")

    ledger[key] = {
        "draft_id": cand.draft_id, "folder": cand.rel, "title": cand.meta.get("title"),
        "column": cand.column, "reason": reason,
        "publish_attempted_at": datetime.now().isoformat(timespec="seconds"),
        "send_arm": send_arm(date.today()),      # 發文時間實驗的組別，事後拿來比開信／參與
    }
    _save_ledger(ledger)
    api.prepublish_draft(int(cand.draft_id))
    api.publish_draft(int(cand.draft_id), send=True, share_automatically=False)

    url = None
    for _ in range(6):
        url = _readback_url(api, cand.draft_id)
        if url:
            break
        time.sleep(10)
    if url:
        ledger[key].update(post_url=url, published_at=datetime.now().isoformat(timespec="seconds"))
        _save_ledger(ledger)
    return url


def update_fb_link(cand: Candidate, url: str) -> None:
    """這篇的 FB 貼文是草稿階段發的，連結指向訂閱首頁；發布後改成文章本身。"""
    try:
        import httpx
        from dotenv import load_dotenv

        load_dotenv(REPO / ".env")
        fb = json.loads((DRAFTS_DIR / ".fb_posted.json").read_text(encoding="utf-8")).get(cand.rel) or {}
        if fb.get("status") != "posted" or not fb.get("fb_id"):
            return
        token = os.environ["FB_PAGE_ACCESS_TOKEN"]
        base = f"https://graph.facebook.com/v20.0/{fb['fb_id']}"
        message = httpx.get(base, params={"fields": "message", "access_token": token}, timeout=30).json().get("message", "")
        lines = [f"👉 全文在這，歡迎訂閱：{url}" if ln.startswith("👉") else ln for ln in message.splitlines()]
        if lines != message.splitlines():
            httpx.post(base, data={"message": "\n".join(lines), "access_token": token}, timeout=30)
            print("[DailyPublish] FB 貼文連結已改成文章網址")
    except Exception as exc:
        print(f"[DailyPublish] ⚠️ FB 連結沒改到（不影響發布）：{str(exc)[:120]}")


def notify(title: str, message: str) -> None:
    try:
        subprocess.run(["osascript", "-e", f'display notification "{message}" with title "{title}"'],
                       timeout=10, check=False)
    except Exception:
        pass


def production_running() -> bool:
    if EDITORIAL_WANT.exists():
        return True
    try:
        pid = int((LOCAL_LOCK / "pid").read_text().strip())
        os.kill(pid, 0)
        return True
    except Exception:
        return False


